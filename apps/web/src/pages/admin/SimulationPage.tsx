const PATH = '/api/admin/simulation';
/** While a simulation runs, its progress is read again this often. */
export const SIMULATION_POLL_MS = 1000;

type SourceKind = SimulationSource['kind'];
type PaceKind = SimulationPace['kind'];

const STATUS_TEXT: Record<SimulationStatus, string> = {
  running: 'In corso',
  paused: 'In pausa',
  stopped: 'Fermata',
  finished: 'Finita',
};

const STATUS_CLASS: Record<SimulationStatus, string> = {
  running: 'bg-success-soft text-text',
  paused: 'bg-surface-2 text-text',
  stopped: 'bg-surface-2 text-muted',
  finished: 'bg-surface-2 text-muted',
};

/** Pure: milliseconds as «m:ss» (or «h:mm:ss» from one hour). */
export function formatClock(ms: number): string {
  const total = Math.max(0, Math.round(ms / 1000));
  const h = Math.floor(total / 3600);
  const m = Math.floor((total % 3600) / 60);
  const s = String(total % 60).padStart(2, '0');
  return h > 0 ? `${h}:${String(m).padStart(2, '0')}:${s}` : `${m}:${s}`;
}

/** Pure: how the pace of a simulation is read on the page. */
export function paceText(pace: SimulationPace | null): string {
  if (!pace) return 'Tempi non più disponibili';
  if (pace.kind === 'speed') return `Velocità ${pace.speed}× sul ritmo reale`;
  return `Set da ${pace.setSeconds} s, pausa tra i set di ${pace.breakSeconds} s`;
}

const active = (s: SimulationSummary | null): boolean => s?.status === 'running' || s?.status === 'paused';

/**
 * «Simulazione» (admin; the superadmin on the client chosen): a random match (generated by the simulator) or an
 * imported `.dvw` is played by the server, with the duration of the sets or a speed, on a link of its own (with QR)
 * to open on TV, tablet or phone. Commands: Avvia, Pausa, Riprendi, Ferma, Ricomincia, Elimina; the progress comes from
 * the server every second while it runs.
 */
export function SimulationPage() {
  const errorMessage = useApiError();
  const load = useCallback((signal: AbortSignal) => apiRequest(PATH, SimulationResponseSchema, { signal }), []);
  const initial = useAsync(load);
  const [data, setData] = useState<SimulationResponse | null>(null);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    document.title = 'Simulazione · Area riservata';
  }, []);
  useEffect(() => {
    if (initial.data) setData(initial.data);
  }, [initial.data]);

  const sim = data?.simulation ?? null;
  const running = sim?.status === 'running';
  // While it runs: the progress, from the server.
  useEffect(() => {
    if (!running) return;
    const controller = new AbortController();
    const timer = setInterval(() => {
      apiRequest(PATH, SimulationResponseSchema, { signal: controller.signal }).then(setData, (err: unknown) => {
        if (!(err instanceof DOMException && err.name === 'AbortError')) setError(errorMessage(err));
      });
    }, SIMULATION_POLL_MS);
    return () => {
      clearInterval(timer);
      controller.abort();
    };
  }, [running, errorMessage]);

  const run = async (action: () => Promise<SimulationResponse | null>): Promise<void> => {
    setBusy(true);
    setError(null);
    try {
      const next = await action();
      setData(next ?? (await apiRequest(PATH, SimulationResponseSchema)));
    } catch (err) {
      setError(errorMessage(err));
    } finally {
      setBusy(false);
    }
  };
  const command = (name: SimulationCommand) =>
    void run(() => apiRequest(`${PATH}/${name}`, SimulationResponseSchema, { method: 'POST', body: {} }));
  const remove = () =>
    void run(async () => {
      await apiCommand(PATH, { method: 'DELETE' });
      return null;
    });

  if (!data) {
    return (
      <Card title="Simulazione">
        {initial.error !== null ? (
          <ErrorBox onRetry={initial.reload}>{errorMessage(initial.error)}</ErrorBox>
        ) : (
          <Spinner label="Caricamento della simulazione…" />
        )}
      </Card>
    );
  }

  return (
    <div className="grid gap-4 lg:grid-cols-[minmax(0,26rem)_minmax(0,1fr)]">
      <StartForm
        data={data}
        disabled={busy || active(sim)}
        locked={active(sim)}
        onStart={(body) => run(() => apiRequest(PATH, SimulationResponseSchema, { method: 'POST', body }))}
      />
      <div className="space-y-4">
        {error && <ErrorBox>{error}</ErrorBox>}
        <Card
          title="Avanzamento"
          subtitle="La partita simulata non entra nel canale del club, nel calendario, tra le partite né nella partita live."
        >
          {sim ? (
            <Progress sim={sim} busy={busy} onCommand={command} onRemove={remove} />
          ) : (
            <Empty>Nessuna simulazione. Scegli la partita e i tempi, poi premi «Avvia».</Empty>
          )}
        </Card>
        {sim?.link && (
          <Card title="Link della simulazione" subtitle="Aprilo sulla TV, sul tablet o sul telefono.">
            <div className="flex flex-wrap items-start gap-4">
              <ShareQr url={sim.link.shortUrl} code={sim.link.shortCode} />
              <div className="min-w-0 basis-full space-y-2 text-sm sm:basis-0 sm:flex-1">
                <a
                  href={sim.link.shortUrl}
                  target="_blank"
                  rel="noopener noreferrer"
                  className="break-all font-medium text-primary underline"
                >
                  {sim.link.shortUrl}
                </a>
                <p className="text-muted">
                  Mostra la simulazione con la grafica del cliente: pause, avvisi, diapositive e punti in sequenza. Il
                  link resta lo stesso per le simulazioni successive e si cancella con la partita.
                </p>
              </div>
            </div>
          </Card>
        )}
      </div>
    </div>
  );
}

function Progress({
  sim,
  busy,
  onCommand,
  onRemove,
}: {
  sim: SimulationSummary;
  busy: boolean;
  onCommand: (c: SimulationCommand) => void;
  onRemove: () => void;
}) {
  const share = sim.linesTotal > 0 ? Math.round((sim.linesSent / sim.linesTotal) * 100) : 0;
  const teams = sim.homeName || sim.awayName ? `${sim.homeName ?? 'Casa'} – ${sim.awayName ?? 'Ospiti'}` : null;
  return (
    <div className="space-y-4" data-testid="simulation">
      <div className="flex flex-wrap items-center gap-2">
        <span className={`rounded-button px-2 py-0.5 text-sm font-semibold ${STATUS_CLASS[sim.status]}`}>
          {STATUS_TEXT[sim.status]}
        </span>
        <span className="text-sm text-muted">{sim.source}</span>
      </div>
      {teams && <p className="font-display text-xl font-semibold text-text">{teams}</p>}
      <dl className="grid grid-cols-2 gap-3 text-sm sm:grid-cols-4">
        <Stat label="Set" value={sim.set > 0 ? String(sim.set) : '–'} />
        <Stat label="Punteggio" value={`${sim.score.home}-${sim.score.away}`} />
        <Stat label="Set vinti" value={`${sim.setsWon.home}-${sim.setsWon.away}`} />
        <Stat label="Righe" value={`${sim.linesSent} / ${sim.linesTotal}`} />
      </dl>
      <div>
        <div
          role="progressbar"
          aria-label="Righe inviate"
          aria-valuemin={0}
          aria-valuemax={100}
          aria-valuenow={share}
          className="h-2 overflow-hidden rounded-button bg-surface-2"
        >
          <div
            className="h-full bg-primary transition-[width] motion-reduce:transition-none"
            style={{ width: `${share}%` }}
          />
        </div>
        <p className="mt-1 text-sm text-muted">
          {sim.pace
            ? `Trascorso ${formatClock(sim.elapsedMs)} · rimanente ${formatClock(sim.remainingMs)} · ${paceText(sim.pace)}`
            : paceText(null)}
        </p>
      </div>
      {sim.notice && (
        <p role="status" className="rounded-card bg-surface-2 px-3 py-2 text-sm text-text">
          {sim.notice}
        </p>
      )}
      <div className="flex flex-wrap gap-2">
        {sim.status === 'running' && (
          <Button onClick={() => onCommand('pause')} disabled={busy}>
            Pausa
          </Button>
        )}
        {sim.status === 'paused' && (
          <Button variant="primary" onClick={() => onCommand('resume')} disabled={busy}>
            Riprendi
          </Button>
        )}
        {active(sim) && (
          <Button onClick={() => onCommand('stop')} disabled={busy}>
            Ferma
          </Button>
        )}
        {sim.pace && (
          <Button onClick={() => onCommand('restart')} disabled={busy}>
            Ricomincia
          </Button>
        )}
        <ConfirmButton label="Elimina" confirmLabel="Elimina partita e link" onConfirm={onRemove} busy={busy} />
      </div>
      {sim.deleteAt && (
        <p className="text-xs text-muted">
          Partita e link si cancellano da soli il {formatDateTime(sim.deleteAt)} (6 ore dopo la fine o la pausa).
        </p>
      )}
    </div>
  );
}

function Stat({ label, value }: { label: string; value: string }) {
  return (
    <div className="rounded-card bg-surface-2 px-3 py-2">
      <dt className="text-xs text-muted">{label}</dt>
      <dd className="font-display text-lg font-semibold tabular-nums text-text">{value}</dd>
    </div>
  );
}

const SOURCE_OPTIONS: { value: SourceKind; label: string }[] = [
  { value: 'generated', label: 'Casuale' },
  { value: 'upload', label: 'Importa file .dvw' },
];
const PACE_OPTIONS: { value: PaceKind; label: string }[] = [
  { value: 'duration', label: 'Durata' },
  { value: 'speed', label: 'Velocità' },
];
const SETS_OPTIONS = [3, 4, 5].map((n) => ({ value: n, label: `${n} set` }));
const SPEED_OPTIONS = SIMULATION_SPEEDS.map((s) => ({ value: s, label: `${s}×` }));

function StartForm({
  data,
  disabled,
  locked,
  onStart,
}: {
  data: SimulationResponse;
  disabled: boolean;
  /** A simulation is running or paused: only one at a time. */
  locked: boolean;
  onStart: (body: unknown) => Promise<void>;
}) {
  const [sourceKind, setSourceKind] = useState<SourceKind>('generated');
  const [sets, setSets] = useState(3);
  const [seed, setSeed] = useState('');
  const [clubTeams, setClubTeams] = useState(true);
  const [file, setFile] = useState<File | null>(null);
  const [paceKind, setPaceKind] = useState<PaceKind>('duration');
  const [setSeconds, setSetSeconds] = useState(String(SIMULATION_SET_SECONDS.default));
  const [breakSeconds, setBreakSeconds] = useState(String(SIMULATION_BREAK_SECONDS.default));
  const [speed, setSpeed] = useState<SimulationSpeed>(5);
  const [problem, setProblem] = useState<string | null>(null);

  const submit = async (e: FormEvent): Promise<void> => {
    e.preventDefault();
    setProblem(null);
    let source: unknown;
    if (sourceKind === 'generated') {
      source = { kind: 'generated', sets, clubTeams, ...(seed.trim() ? { seed: Number(seed) } : {}) };
    } else {
      if (!file) return setProblem('Scegli un file .dvw.');
      if (file.size > SIMULATION_UPLOAD_MAX_BYTES)
        return setProblem(`File troppo grande: al massimo ${SIMULATION_UPLOAD_MAX_BYTES / (1024 * 1024)} MB.`);
      source = { kind: 'upload', fileName: file.name, data: await fileToBase64(file) };
    }
    const pace =
      paceKind === 'speed'
        ? { kind: 'speed', speed }
        : { kind: 'duration', setSeconds: Number(setSeconds), breakSeconds: Number(breakSeconds) };
    const body = StartSimulationRequestSchema.safeParse({ source, pace });
    if (!body.success) {
      const field = body.error.issues[0]?.path.join('.') ?? '';
      setProblem(
        field.startsWith('pace')
          ? `Durata di un set tra ${SIMULATION_SET_SECONDS.min} e ${SIMULATION_SET_SECONDS.max} secondi, pausa tra ${SIMULATION_BREAK_SECONDS.min} e ${SIMULATION_BREAK_SECONDS.max}.`
          : field.startsWith('source.seed')
            ? 'Il seme è un numero intero da 1 in su.'
            : 'Controlla la partita scelta.',
      );
      return;
    }
    await onStart(body.data);
  };

  return (
    <Card title="Nuova simulazione" subtitle="Il server gioca la partita come farebbe l’agente, riga per riga.">
      <form onSubmit={(e) => void submit(e)} className="space-y-4" noValidate>
        <fieldset className="space-y-3" disabled={disabled}>
          <legend className="mb-2 text-sm font-medium text-text">Partita</legend>
          <Segmented label="Partita" options={SOURCE_OPTIONS} value={sourceKind} onChange={setSourceKind} />
          {sourceKind === 'generated' && (
            <div className="space-y-3">
              <Segmented label="Set da giocare" options={SETS_OPTIONS} value={sets} onChange={setSets} />
              <label className="flex items-start gap-2 text-sm text-text">
                <input
                  type="checkbox"
                  checked={clubTeams}
                  onChange={(e) => setClubTeams(e.target.checked)}
                  className="mt-0.5 size-4"
                />
                <span>
                  Usa le squadre del club
                  {data.clubTeams && (
                    <span className="block text-xs text-muted">
                      {data.clubTeams.home} – {data.clubTeams.away}
                    </span>
                  )}
                </span>
              </label>
              <Field label="Seme (facoltativo)" hint="Stesso seme, stessa partita; vuoto: una partita a caso.">
                <input
                  inputMode="numeric"
                  value={seed}
                  onChange={(e) => setSeed(e.target.value)}
                  className={inputClass}
                />
              </Field>
            </div>
          )}
          {sourceKind === 'upload' && (
            <Field
              label="File .dvw"
              hint={`Un file di DataVolley, al massimo ${SIMULATION_UPLOAD_MAX_BYTES / (1024 * 1024)} MB. Le righe non riconosciute restano, come con l’agente.`}
            >
              <input
                type="file"
                accept=".dvw"
                onChange={(e) => setFile(e.target.files?.[0] ?? null)}
                className={inputClass}
              />
            </Field>
          )}
        </fieldset>
        <fieldset className="space-y-3" disabled={disabled}>
          <legend className="mb-2 text-sm font-medium text-text">Tempi</legend>
          <Segmented label="Tempi" options={PACE_OPTIONS} value={paceKind} onChange={setPaceKind} />
          {paceKind === 'duration' ? (
            <div className="grid grid-cols-2 gap-3">
              <Field label="Durata di un set (s)">
                <input
                  type="number"
                  min={SIMULATION_SET_SECONDS.min}
                  max={SIMULATION_SET_SECONDS.max}
                  value={setSeconds}
                  onChange={(e) => setSetSeconds(e.target.value)}
                  className={inputClass}
                />
              </Field>
              <Field label="Pausa tra i set (s)">
                <input
                  type="number"
                  min={SIMULATION_BREAK_SECONDS.min}
                  max={SIMULATION_BREAK_SECONDS.max}
                  value={breakSeconds}
                  onChange={(e) => setBreakSeconds(e.target.value)}
                  className={inputClass}
                />
              </Field>
            </div>
          ) : (
            <div className="space-y-1">
              <Segmented label="Velocità" options={SPEED_OPTIONS} value={speed} onChange={setSpeed} />
              <p className="text-xs text-muted">
                Sul ritmo reale delle righe (gli orari del file); senza orari, un ritmo medio realistico.
              </p>
            </div>
          )}
        </fieldset>
        {problem && <ErrorBox>{problem}</ErrorBox>}
        <Button type="submit" variant="primary" disabled={disabled}>
          Avvia
        </Button>
        {locked && <p className="text-xs text-muted">Una simulazione alla volta: fermala per avviarne un’altra.</p>}
      </form>
    </Card>
  );
}
