import { z } from 'zod';

/**
 * Statistiche delle visualizzazioni della pagina pubblica: contratti del messaggio `hello` (WebSocket pubblico) e delle
 * rotte `GET /api/admin/stats/*`. Nessun dato personale: niente IP, niente user agent, niente identificativi
 * persistenti; l'id di visita esiste solo nella memoria della pagina e non viene mai salvato.
 */

export const VISIT_DEVICES = ['tv', 'tablet', 'phone'] as const;
export const VisitDeviceSchema = z.enum(VISIT_DEVICES);
export type VisitDevice = z.infer<typeof VisitDeviceSchema>;

/** `qr`: opened from the QR code (`?q=1`); `link`: any other way. */
export const VISIT_SOURCES = ['qr', 'link'] as const;
export const VisitSourceSchema = z.enum(VISIT_SOURCES);
export type VisitSource = z.infer<typeof VisitSourceSchema>;

/** Random id of a page visit (16-64 URL-safe characters), generated by the page and kept only in its memory. */
export const VISIT_ID_PATTERN = /^[A-Za-z0-9_-]{16,64}$/;

/** Query parameter added to the address encoded in a QR code. */
export const QR_QUERY_PARAM = 'q';

/**
 * Client→server, once per public WebSocket, right after it opens: how the page was opened. A reconnection within 30
 * seconds with the same `visit` is the same visit.
 */
export const HelloMessageSchema = z.strictObject({
  type: z.literal('hello'),
  visit: z.string().regex(VISIT_ID_PATTERN),
  device: VisitDeviceSchema,
  source: VisitSourceSchema,
  /** Installed as an app (display-mode standalone or fullscreen). */
  app: z.boolean(),
});
export type HelloMessage = z.infer<typeof HelloMessageSchema>;

const DAY_PATTERN = /^\d{4}-\d{2}-\d{2}$/;
const DayStringSchema = z
  .string()
  .regex(DAY_PATTERN)
  .refine((s) => {
    const d = new Date(`${s}T00:00:00Z`);
    return !Number.isNaN(d.getTime()) && d.toISOString().startsWith(s);
  }, 'Data non valida');

/** Longest period asked in one call. */
export const STATS_MAX_DAYS = 366;

/** Period of the statistics, in days of Rome (`YYYY-MM-DD`, both included); missing: the last 30 days. */
export const StatsPeriodQuerySchema = z
  .strictObject({ from: DayStringSchema.optional(), to: DayStringSchema.optional() })
  .refine((q) => !q.from || !q.to || q.from <= q.to, { message: 'Periodo non valido', path: ['from'] })
  .refine((q) => !q.from || !q.to || (Date.parse(q.to) - Date.parse(q.from)) / 86_400_000 < STATS_MAX_DAYS, {
    message: 'Periodo troppo lungo',
    path: ['to'],
  });
export type StatsPeriodQuery = z.infer<typeof StatsPeriodQuerySchema>;

const Count = z.number().int().nonnegative();

export const StatsTotalsSchema = z.object({
  visits: Count,
  qrVisits: Count,
  appVisits: Count,
  totalSeconds: Count,
  /** Mean length of a visit, in seconds (0 without visits). */
  avgSeconds: Count,
  peak: Count,
  /** Minute of the highest peak (ISO); null when only the totals of old days are left. */
  peakAt: z.iso.datetime().nullable(),
});
export type StatsTotals = z.infer<typeof StatsTotalsSchema>;

export const StatsMatchRowSchema = z.object({
  /** null: visits with no match yet («Prossima partita» before the start). */
  matchId: z.uuid().nullable(),
  label: z.string(),
  visits: Count,
  qrVisits: Count,
  totalSeconds: Count,
  avgSeconds: Count,
  peak: Count,
  peakAt: z.iso.datetime().nullable(),
});
export type StatsMatchRow = z.infer<typeof StatsMatchRowSchema>;

export const StatsLinkRowSchema = z.object({
  /** null: the link was deleted since. */
  shareTokenId: z.uuid().nullable(),
  label: z.string(),
  /** What the link shows: the channel of the club, one match of the calendar, a fixed match, or a deleted link. */
  kind: z.enum(['channel', 'fixture', 'match', 'deleted']),
  visits: Count,
  qrVisits: Count,
  avgSeconds: Count,
});
export type StatsLinkRow = z.infer<typeof StatsLinkRowSchema>;

export const StatsDayRowSchema = z.object({
  day: z.string().regex(DAY_PATTERN),
  visits: Count,
  totalSeconds: Count,
  peak: Count,
});
export type StatsDayRow = z.infer<typeof StatsDayRowSchema>;

export const StatsOverviewSchema = z.object({
  from: z.string().regex(DAY_PATTERN),
  to: z.string().regex(DAY_PATTERN),
  totals: StatsTotalsSchema,
  devices: z.object({ tv: Count, tablet: Count, phone: Count }),
  matches: z.array(StatsMatchRowSchema),
  links: z.array(StatsLinkRowSchema),
  daily: z.array(StatsDayRowSchema),
});
export type StatsOverview = z.infer<typeof StatsOverviewSchema>;

/** «Adesso»: spectators connected right now (live in the memory of the server). */
export const StatsNowSchema = z.object({
  viewers: Count,
  live: z.object({ matchId: z.uuid(), label: z.string() }).nullable(),
  matches: z.array(z.object({ matchId: z.uuid().nullable(), label: z.string(), viewers: Count })),
  links: z.array(z.object({ label: z.string(), viewers: Count })),
});
export type StatsNow = z.infer<typeof StatsNowSchema>;

/** Spectators connected, minute by minute, during a match. */
export const StatsCurveSchema = z.object({
  matchId: z.uuid(),
  points: z.array(z.object({ at: z.iso.datetime(), viewers: Count })),
});
export type StatsCurve = z.infer<typeof StatsCurveSchema>;

/** Days of detail kept; older days stay only as daily totals. */
export const STATS_DETAIL_DAYS = 90;
