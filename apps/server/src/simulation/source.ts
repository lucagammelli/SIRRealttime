import { decodeDvw, parseDvw } from '@sir/dvw-parser';
import type { PlaybackLine } from '@sir/dvw-simulator';
import { generateMatch, renderDvw } from '@sir/dvw-simulator';
import {
  INGEST_MAX_LINES,
  INGEST_PROTOCOL,
  IngestRequestSchema,
  SCOUT_SECTION_MARKER,
  SIMULATION_UPLOAD_MAX_BYTES,
  splitDvwText,
} from '@sir/shared';
import { HttpError } from '../lib/errors.js';

/** A match ready to be replayed: the header of the file, its scout lines and what the timing needs of them. */
export interface LoadedMatch {
  /** Where it comes from, as shown on the page. */
  label: string;
  header: string;
  lines: string[];
  timing: PlaybackLine[];
}

/** A file that cannot be replayed: 422 with the reason in Italian (shown by the page). */
export const dvwRejected = (message: string): HttpError => new HttpError(422, 'DVW_REJECTED', message);

/** A file larger than SIMULATION_UPLOAD_MAX_BYTES. */
export const dvwTooLarge = (): HttpError =>
  new HttpError(
    413,
    'DVW_TOO_LARGE',
    `File troppo grande: al massimo ${Math.round(SIMULATION_UPLOAD_MAX_BYTES / (1024 * 1024))} MB`,
  );

/** The line that opens the scout section (as `splitDvwText` looks for it). */
const SCOUT_SECTION = /^[ \t]*\[3SCOUT\][ \t]*$/m;

/**
 * Pure: a `.dvw` file (bytes) read as the agent would send it: Windows-1252 or UTF-8 (`decodeDvw`), header and scout
 * lines (`splitDvwText`), checked against the contract of the ingest (lines and header), at most `maxLines` lines.
 * A malformed line is kept: the parser makes it an `unknown` action, as for the agent.
 */
export function fileMatch(bytes: Uint8Array, label: string, maxLines: number): LoadedMatch {
  if (bytes.length > SIMULATION_UPLOAD_MAX_BYTES) throw dvwTooLarge();
  const text = decodeDvw(bytes);
  if (!SCOUT_SECTION.test(text))
    throw dvwRejected(`Il file non è un .dvw di DataVolley: manca la sezione ${SCOUT_SECTION_MARKER}`);
  const { header, scoutLines } = splitDvwText(text);
  if (scoutLines.length === 0) throw dvwRejected('Il file non contiene righe di scout');
  const limit = Math.min(maxLines, INGEST_MAX_LINES);
  if (scoutLines.length > limit) throw dvwRejected(`Il file ha troppe righe di scout (al massimo ${limit})`);
  const request = IngestRequestSchema.safeParse({
    protocol: INGEST_PROTOCOL,
    matchKey: 'controllo',
    seq: 0,
    kind: 'snapshot',
    fromIndex: 0,
    lines: scoutLines,
    header,
    contentHash: '0'.repeat(64),
  });
  if (!request.success)
    throw dvwRejected('Il file contiene righe non valide (troppo lunghe o con caratteri non ammessi)');
  const timing = parseDvw(text).scout.map((entry) => ({ kind: entry.kind, time: entry.time }));
  return { label, header, lines: scoutLines, timing };
}

/**
 * Pure: a match generated by `tools/dvw-simulator` (`generateMatch`), written as DataVolley would (`renderDvw`): the
 * header of the empty file (no partial scores yet) and all the scout lines.
 */
export function generatedMatch(options: {
  sets: 3 | 4 | 5;
  seed: number;
  homeName?: string | undefined;
  awayName?: string | undefined;
}): LoadedMatch {
  const match = generateMatch({
    seed: options.seed,
    sets: options.sets,
    ...(options.homeName ? { homeName: options.homeName } : {}),
    ...(options.awayName ? { awayName: options.awayName } : {}),
  });
  const decode = (bytes: Uint8Array): string => new TextDecoder('utf-8').decode(bytes);
  const { header } = splitDvwText(decode(renderDvw(match, 0, { encoding: 'utf8' })));
  const full = decode(renderDvw(match, match.lines.length, { encoding: 'utf8' }));
  const lines = splitDvwText(full).scoutLines;
  const timing = parseDvw(full).scout.map((entry) => ({ kind: entry.kind, time: entry.time }));
  return { label: `Partita casuale (${options.sets} set, seme ${options.seed})`, header, lines, timing };
}
